CREATE TABLE mail_delivery (
    id uuid PRIMARY KEY,
    challenge_id uuid NOT NULL,
    deduplication_key varchar(128) NOT NULL UNIQUE,
    envelope_digest bytea NOT NULL CHECK(octet_length(envelope_digest)=32),
    template_code varchar(64) NOT NULL,
    template_version integer NOT NULL CHECK(template_version>=1),
    state varchar(16) NOT NULL CHECK(state IN ('READY','LEASED','ACCEPTED','CANCELLED','UNKNOWN','FAILED')),
    available_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    lease_owner varchar(128),
    lease_until timestamptz,
    attempt_count integer NOT NULL DEFAULT 0 CHECK(attempt_count>=0),
    max_attempts integer NOT NULL DEFAULT 3 CHECK(max_attempts BETWEEN 1 AND 10),
    provider_message_id varchar(256),
    message_ciphertext bytea,
    message_nonce bytea CHECK(message_nonce IS NULL OR octet_length(message_nonce)=12),
    message_key_version smallint NOT NULL CHECK(message_key_version>0),
    last_error_code varchar(64),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    version bigint NOT NULL DEFAULT 1 CHECK(version BETWEEN 1 AND 9007199254740991),
    CHECK(expires_at>created_at),
    CHECK((message_ciphertext IS NULL)=(message_nonce IS NULL)),
    CHECK(state NOT IN ('READY','LEASED') OR message_ciphertext IS NOT NULL),
    CHECK(state NOT IN ('ACCEPTED','CANCELLED','FAILED') OR message_ciphertext IS NULL),
    CHECK((state='LEASED')=(lease_owner IS NOT NULL AND lease_until IS NOT NULL))
);
CREATE INDEX mail_delivery_due ON mail_delivery(state,available_at,expires_at);
CREATE TABLE mail_delivery_attempt (
    id uuid PRIMARY KEY,
    delivery_id uuid NOT NULL REFERENCES mail_delivery(id) ON DELETE RESTRICT,
    attempt_number integer NOT NULL CHECK(attempt_number>=1),
    status varchar(24) NOT NULL CHECK(status IN ('STARTED','ACCEPTED','RETRYABLE_FAILED','PERMANENT_FAILED','UNKNOWN','CANCELLED')),
    started_at timestamptz NOT NULL,
    finished_at timestamptz,
    provider_message_id varchar(256),
    error_code varchar(64),
    UNIQUE(delivery_id,attempt_number),
    CHECK((status='STARTED')=(finished_at IS NULL))
);
